#!/usr/bin/env python3
"""Writes sw.js: the service worker that lets Voxloop Studio open and work without internet.
Run from the project folder after changing any file:   python3 tools/build-sw.py
The cache name contains a hash of every cached file, so a changed file means a new cache and the app updates itself
the next time it is opened with internet."""
import hashlib, os, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
files = ["index.html", "manifest.webmanifest", "apple-touch-icon.png", "logo-mark.png"]
for d in ("js", "css", "lib", "assets", "icons"):
    for dp, _, fs in os.walk(d):
        for f in sorted(fs):
            if f.startswith("."): continue
            files.append(os.path.join(dp, f).replace(os.sep, "/"))
files = sorted(set(files))
h = hashlib.sha256()
for f in files:
    h.update(f.encode()); h.update(open(f, "rb").read())
version = "vl-" + h.hexdigest()[:12]
sw = '''/* Voxloop Studio service worker (generated by tools/build-sw.py: do not edit by hand) */
const VERSION = "%s";
const SHELL = %s;
const FONTS = "vl-fonts";

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== VERSION && k !== FONTS).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);

  // fonts from Google: show what is stored first, refresh quietly (the app has fallback fonts if they were never loaded)
  if (url.hostname === "fonts.googleapis.com" || url.hostname === "fonts.gstatic.com") {
    e.respondWith(caches.open(FONTS).then(async (c) => {
      const hit = await c.match(req);
      const net = fetch(req).then((r) => { if (r && (r.ok || r.type === "opaque")) c.put(req, r.clone()); return r; }).catch(() => hit);
      return hit || net;
    }));
    return;
  }
  if (url.origin !== self.location.origin) return;

  // opening the app: the newest page if the network answers quickly, otherwise the stored one
  if (req.mode === "navigate") {
    e.respondWith((async () => {
      const cache = await caches.open(VERSION);
      try {
        const ctl = new AbortController(); const t = setTimeout(() => ctl.abort(), 4000);
        const r = await fetch(req, { signal: ctl.signal }); clearTimeout(t);
        if (r && r.ok) { cache.put("index.html", r.clone()); return r; }
      } catch (_) { /* offline or slow */ }
      return (await cache.match("index.html")) || (await cache.match("./")) || Response.error();
    })());
    return;
  }

  // everything else of the app: from the stored copy (the cache name changes whenever a file changes)
  e.respondWith(caches.open(VERSION).then(async (c) => {
    const hit = await c.match(req, { ignoreSearch: true });
    if (hit) return hit;
    try { const r = await fetch(req); if (r && r.ok) c.put(req, r.clone()); return r; } catch (err) { return Response.error(); }
  }));
});
''' % (version, json.dumps(files, indent=1))
open("sw.js", "w").write(sw)
print(version, len(files), "files")
